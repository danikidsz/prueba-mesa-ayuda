DROP TABLE IF EXISTS historial_estado;
DROP TABLE IF EXISTS adjuntos;
DROP TABLE IF EXISTS tickets;
DROP TABLE IF EXISTS usuarios;
DROP TABLE IF EXISTS areas;

CREATE TABLE areas (
  id_area        INT PRIMARY KEY,
  nombre         VARCHAR(80)  NOT NULL,
  sede           VARCHAR(60)  NOT NULL,
  responsable    VARCHAR(120)
);

CREATE TABLE usuarios (
  id_usuario     INT PRIMARY KEY,
  correo         VARCHAR(120) NOT NULL UNIQUE,
  nombre         VARCHAR(120) NOT NULL,
  id_area        INT NOT NULL,
  activo         CHAR(1) NOT NULL DEFAULT 'S',
  CONSTRAINT fk_usuario_area FOREIGN KEY (id_area) REFERENCES areas(id_area)
);

CREATE TABLE tickets (
  id_ticket        INT PRIMARY KEY,
  codigo           VARCHAR(20) NOT NULL UNIQUE,
  id_usuario       INT NOT NULL,
  id_area          INT NOT NULL,
  categoria        VARCHAR(60),
  prioridad        VARCHAR(20),
  canal            VARCHAR(30),
  asunto           VARCHAR(200),
  descripcion      TEXT,
  estado           VARCHAR(30) NOT NULL,
  fecha_creacion   DATETIME NOT NULL,
  fecha_cierre     DATETIME NULL,
  reaperturas      INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_ticket_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario),
  CONSTRAINT fk_ticket_area    FOREIGN KEY (id_area)    REFERENCES areas(id_area)
);

CREATE TABLE adjuntos (
  id_adjunto     INT PRIMARY KEY,
  id_ticket      INT NOT NULL,
  nombre_archivo VARCHAR(200) NOT NULL,
  tamano_kb      INT,
  CONSTRAINT fk_adjunto_ticket FOREIGN KEY (id_ticket) REFERENCES tickets(id_ticket)
);

CREATE TABLE historial_estado (
  id_historial   INT PRIMARY KEY,
  id_ticket      INT NOT NULL,
  estado_anterior VARCHAR(30),
  estado_nuevo    VARCHAR(30) NOT NULL,
  fecha_cambio    DATETIME NOT NULL,
  usuario_cambio  VARCHAR(120),
  CONSTRAINT fk_hist_ticket FOREIGN KEY (id_ticket) REFERENCES tickets(id_ticket)
);

